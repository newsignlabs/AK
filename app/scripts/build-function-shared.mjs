// Bundles the site's validation schema, pricing logic and content into the
// Catalyst function so both sides validate and price enquiries identically.
// Run after changing src/lib/{schema,estimate,whatsapp}.ts or content JSON.
import { build } from 'esbuild';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const outfile = path.resolve(root, '../functions/enquiry/lib/shared.js');

await build({
  entryPoints: [path.join(root, 'src/lib/shared-entry.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  minify: true,
  legalComments: 'none',
  banner: { js: '// GENERATED by app/scripts/build-function-shared.mjs — do not edit by hand.' },
  logLevel: 'info',
});
