// Bundles shared site code into the Catalyst functions so both sides use
// exactly the same rules:
//  - enquiry: validation schema, pricing logic and content
//  - admin:   content-file schemas and cross-reference checks
// Run after changing src/lib/{schema,estimate,whatsapp,content-schema}.ts or content JSON.
import { build } from 'esbuild';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const targets = [
  ['src/lib/shared-entry.ts', '../functions/enquiry/lib/shared.js'],
  ['src/lib/admin-shared-entry.ts', '../functions/admin/lib/shared.js'],
];

for (const [entry, out] of targets) {
  await build({
    entryPoints: [path.join(root, entry)],
    outfile: path.resolve(root, out),
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    minify: true,
    legalComments: 'none',
    banner: { js: '// GENERATED by app/scripts/build-function-shared.mjs — do not edit by hand.' },
    logLevel: 'info',
  });
}
